w("RUN 2 -- WHAT THE RULES WERE MADE ON")
w("-" * 68)
w(f"  {len(rules)} rules admitted across {h2['monitor']['v2_windows_closed']} windows, all dry run.")
for (src, dst, port, cls), n in sorted(tally.items(), key=lambda kv: -kv[1]):
    w(f"    {n} x {cls:<17} {src:>10} -> {dst}:{port}")
w("  What each of those conversations was, from the traffic script:")
w("    10.0.0.7/8 -> 10.0.0.3:80 and 10.0.0.9/10 -> 10.0.0.1:80   benign HTTP fetches")
