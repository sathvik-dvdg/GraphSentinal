w("    OVS (s1) -> enforcement_daemon.py `ovs-ofctl dump-flows s1` -> flow_parser")
w("    -> monitor -> provenance gate -> v2 client -> inference service -> rules")
w("    accepted and logged by the backend.")
w("  The `data_source: ovs` tag on every flow was set by flow_parser from the dump")
w("  text. Nothing was tagged by hand and the provenance gate was not changed.")
w("")
w("ROUTE")
w("  Route B, local, no Docker. NOT Colab and NOT a replayed capture: the backend")
w("  polled a live switch every 5 s for the whole run.")
w("    WSL2 Ubuntu 26.04.1, kernel 6.18.33.2-microsoft-standard-WSL2")
w("    Open vSwitch 3.7.1, kernel datapath (openvswitch module loaded), Mininet 2.3.0")
w("    topology: mininet/topologies/base_topology_headless.py, unmodified")
w("      (10 hosts 10.0.0.1-10, one switch s1, fail_mode secure, controller")
w("       ovs-testcontroller via Mininet's OVSController -- it installs one")
w("       exact-match flow per conversation, idle_timeout 60)")
w("    daemon: backend/scripts/enforcement_daemon.py, unmodified, in WSL as root,")
w("      127.0.0.1:50051, reached from Windows through WSL2 localhost forwarding")
w("    backend and inference service: the two uvicorn processes of RUN_GUIDE.md")
w("      section 5, on Windows, Python 3.10.10, torch 2.13.0+cpu. No Ganache, no")
w("      frontend. ENFORCEMENT_MODE=simulated, THREAT_THRESHOLD=0.75,")
w("      DEMO_FALLBACK_FLOWS=false, GS2_ENABLED=true.")
w("    backend started with --log-config so that INFO lines from its own")
w("      `graphsentinel.*` loggers are printed. Under the default start they are")
w("      not: no handler is configured for them and only WARNING and above show.")
w("")
w("TWO RUNS, SAME TRAFFIC SCRIPT")
w("  Run 1 logged rule COUNTS only; the monitor keeps nothing else of a window.")
w("  So one logging change was made (analysis_pipeline_v2.py: one line per rule")
w("  and one per scored window) and the run repeated. Run 2 is the one analysed.")
w("  Both are given below. The two runs are not a variance estimate.")
w("")
w("TRAFFIC (run 2, UTC, from the generator's own log)")
for l in text("traffic.log").splitlines():
    w("  " + l)
w("  All of it was generated by one script written for this run. It is labelled by")
w("  construction (the script knows what it sent), not by a dataset.")
w("")
w("MEMORY")
