"""Assemble ML/retrain_logs/live_loop_run.txt from the run's own outputs. Nothing
here is typed in from memory: the log lines, health payloads and traffic timeline
are read from the files the run wrote."""
import json
import re
from collections import Counter
from pathlib import Path

G = Path("C:/dev/gs_live")
REPO = Path("C:/dev/GraphSentinal")
OUT = REPO / "ML" / "retrain_logs" / "live_loop_run.txt"
CAP = REPO / "ML" / "retrain_logs" / "live_loop"
CAP.mkdir(parents=True, exist_ok=True)


def text(name):
    return (G / name).read_text(encoding="utf-8", errors="replace").replace("\x00", "").replace("\r\n", "\n")


def lines_of(name, keep):
    return [l for l in text(name).splitlines() if keep(l)]


run2_log = lines_of("backend.log", lambda l: l.strip() and "FlowParser" not in l)
run1_log = lines_of("run1_backend.log", lambda l: "graphsentinel" in l)
h1 = json.loads(text("run1_health.json"))
h2 = json.loads(text("run2_health.json"))

# The capture for run 2, raw, as OVS printed it.
cap2 = text("dump_flows_capture.txt")
cap1 = text("run1_dump_flows.txt")
(CAP / "dump_flows_run2.txt").write_text(cap2, encoding="utf-8", newline="\n")
(CAP / "dump_flows_run1.txt").write_text(cap1, encoding="utf-8", newline="\n")

rules = [re.search(r"rule (\S+)/(\S+) on (\S+) -> (\S+?):(\d+) proto", l).groups()
         for l in run2_log if ": rule " in l]
tally = Counter((src, dst, port, cls) for cls, _, src, dst, port in rules)
polls2 = cap2.count("=== ")
dumps = [d for d in cap2.split("=== ")[1:]]
per_dump = [sum(1 for l in d.splitlines()[1:] if "nw_src=" in l or "arp_spa=" in l) for d in dumps]


def mon(h):
    m, c = h["monitor"], h["ml_v2"]["client"]
    return {
        "poll_counts": m["poll_counts"], "last_poll_status": m["last_poll_status"],
        "v2_provenance": m["v2_provenance"], "v2_windows_closed": m["v2_windows_closed"],
        "v2_last_error": m["v2_last_error"],
        "client": {k: c[k] for k in ("windows_seen", "windows_unscored", "unscored_rate",
                                     "flows_sent", "flows_dropped_in_mapping", "last_error")},
        "policy_sha256": h["ml_v2"]["policy"]["sha256"],
        "policy_enforceable": h["ml_v2"]["policy"]["enforceable"],
        "policy_alert_only": h["ml_v2"]["policy"]["alert_only"],
        "policy_dry_run": h["ml_v2"]["policy"]["dry_run"],
        "v1": h["v1"],
    }


out = []
