w("  anything.")
w("")
w("RUN 2 -- THE BACKEND'S OWN LOG (FlowParser failure lines: none)")
w("-" * 68)
for l in run2_log:
    w(l)
w("")
w("RUN 2 -- /health AFTER THE RUN (monitor, v2 client, policy)")
w("-" * 68)
w(json.dumps(mon(h2), indent=2))
